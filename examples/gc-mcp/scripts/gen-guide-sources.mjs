// Fixed public source inputs only. Runtime tools never open these files or user-supplied paths.
import fs from 'node:fs';
import crypto from 'node:crypto';
const root=new URL('../../../',import.meta.url);
const paths={
 principles:'AGENTS.md',
 worker:'internal/bootstrap/packs/core/assets/prompts/graph-worker.md',
 claim:'internal/bootstrap/packs/core/template-fragments/claim-protocol.template.md',
 mail:'internal/bootstrap/packs/core/skills/gc-mail/SKILL.md',
 dispatch:'internal/bootstrap/packs/core/skills/gc-dispatch/SKILL.md',
 mcp:'examples/gc-mcp/README.md',
 reply:'examples/gc-mcp/src/voice.ts',
};
const sources=Object.fromEntries(Object.entries(paths).map(([id,path])=>[id,{repository:'wbern/gascity',path,sha256:crypto.createHash('sha256').update(fs.readFileSync(new URL(path,root))).digest('hex')} ]));
const text='// Generated by scripts/gen-guide-sources.mjs. Review guidance when a source changes.\nexport const GUIDE_SOURCES = '+JSON.stringify(sources,null,2)+' as const;\n';
const target=new URL('../src/guide-sources.ts',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==text)throw Error('Guide provenance drifted; review guide and run npm run gen:guide');}else fs.writeFileSync(target,text);
